def sld():
    s = prs.slides.add_slide(BL)
    b = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height)
    b.fill.solid(); b.fill.fore_color.rgb = BG
    b.line.fill.background(); b.shadow.inherit = False
    return s


def rect(s, x, y, w, h, fill=None):
    sh = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    if fill is None:
        sh.fill.background()
    else:
        sh.fill.solid(); sh.fill.fore_color.rgb = fill
    sh.line.fill.background(); sh.shadow.inherit = False
    return sh


def txt(s, x, y, w, h, t, size=11, bold=False, color=MUT, align=PP_ALIGN.LEFT, sp=1.15, caps=False):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame; tf.word_wrap = True
    tf.margin_left = 0; tf.margin_right = 0; tf.margin_top = 0; tf.margin_bottom = 0
    tf.vertical_anchor = MSO_ANCHOR.TOP; tf.auto_size = None
    for i, ln in enumerate(t.split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align; p.line_spacing = sp
        r = p.add_run(); r.text = ln.upper() if caps else ln
        f = r.font; f.name = "Inter"; f.size = Pt(size); f.bold = bold; f.color.rgb = color
        if caps: r.font._rPr.set('cap', 'all')
    return tb


def hair(s, y, x=M, w=CW, color=LINE):
    rect(s, x, y, w, 0.010, color)


def pic(s, path, x, y, w, h):
    s.shapes.add_picture(path, Inches(x), Inches(y), Inches(w), Inches(h))


def scrim(s, x, y, w, h, steps=70):
    """вертикальное затемнение слева направо"""
    for i in range(steps):
        t = i / steps
        rect(s, x + w * t, y, w / steps + 0.02, h, None)
        sh = s.shapes[-1]
        sh.fill.solid(); sh.fill.fore_color.rgb = BG
        sh.fill.transparency = int(100 - 92 * (1 - t) - 6 * t) if False else None
# прозрачность через xml не нужна: используем полосы разной ширины с наложением
del scrim


def grad(s, x, y, w, h, a0=0.94, steps=90):
    for i in range(steps):
        t = i / steps
        strip = rect(s, x + w * t, y, w / steps + 0.03, h, BG)
        strip.fill.transparency = int((a0 + (0.02 - a0) * t) * 100)


def pagenum(s, n):
    txt(s, 11.95, 7.12, 0.62, 0.22, str(n), 8, False, DIM, PP_ALIGN.RIGHT)


def head(s, kicker, title, size=34, sub=None):
    txt(s, M, 0.66, CW, 0.28, kicker, 8.5, True, ACC, caps=True)
    txt(s, M, 1.02, 11.6, 0.9, title, size, True, W, sp=1.03)
