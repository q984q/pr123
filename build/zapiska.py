FS = "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf"
FSB = "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf"
NAMES = {F: "F1", FB: "F2", FS: "F3", FSB: "F4"}
_f = {}


def fnt(p):
    if p not in _f:
        _f[p] = fitz.Font(fontfile=p)
    return _f[p]


def tw(t, size, path=F):
    return fnt(path).text_length(t, fontsize=size)


def wrap(t, size, maxw, path=F):
    out = []
    for para in t.split("\n"):
        line = ""
        for w in para.split(" "):
            cand = (line + " " + w).strip()
            if tw(cand, size, path) <= maxw or not line:
                line = cand
            else:
                out.append(line); line = w
        out.append(line)
    return out


class Doc:
    def __init__(self):
        self.doc = fitz.open()
        self.page = None
        self.y = 0
        self.n = 0

    def new(self, top=True):
        self.n += 1
        self.page = self.doc.new_page(width=PW, height=PH)
        for p in (F, FB, FS, FSB):
            self.page.insert_font(fontname=NAMES[p], fontfile=p)
        self.y = MG
        if self.n > 1:
            self.page.insert_text((MG, 34), "SOKOL · КОНЦЕПЦИЯ · ЗАПИСКА К ЗАЩИТЕ", fontsize=7.2,
                                  fontname="F2", color=MUT)
            self.page.insert_text((PW - MG - tw(f"{self.n}", 8.4, FS), 34), str(self.n),
                                  fontsize=8.4, fontname="F3", color=MUT)
            self.page.draw_line(fitz.Point(MG, 44), fitz.Point(PW - MG, 44), color=RULE, width=0.8)
            self.y = 62
        return self.page

    def ensure(self, h):
        if self.y + h > PH - MG - 12:
            self.new()

    def para(self, t, size=9.4, color=BODY, path=F, lh=1.55, gap=7, maxw=None, x=MG):
        w = maxw or (PW - 2 * MG - (x - MG))
        lines = wrap(t, size, w, path)
        step = size * lh
        for ln in lines:
            self.ensure(step)
            self.page.insert_text((x, self.y + size * 0.82), ln, fontsize=size,
                                  fontname=NAMES[path], color=color)
            self.y += step
        self.y += gap

    def h1(self, num, title, sub=None):
        self.ensure(78)
        self.y += 10
        self.page.insert_text((MG, self.y + 8), num, fontsize=9, fontname="F2", color=ACC)
        self.page.insert_text((MG + 26, self.y + 12), title, fontsize=19, fontname="F4", color=INK)
        self.y += 30
        self.page.draw_line(fitz.Point(MG, self.y), fitz.Point(PW - MG, self.y), color=INK, width=1.6)
        self.y += 12
        if sub:
            self.para(sub, 9.2, MUT, FS, gap=10)

    def h2(self, label, title=None):
        self.ensure(64)
        self.y += 6
        self.page.insert_text((MG, self.y + 7), label.upper(), fontsize=7.6, fontname="F2", color=ACC)
        self.y += 16
        if title:
            for ln in wrap(title, 12.4, PW - 2 * MG, FB):
                self.page.insert_text((MG, self.y + 10), ln, fontsize=12.4,
                                      fontname=NAMES[FB], color=INK)
                self.y += 17
            self.y += 5
        self.page.draw_line(fitz.Point(MG, self.y), fitz.Point(PW - MG, self.y), color=RULE, width=0.7)
        self.y += 9

    def bullets(self, items, size=9.2, indent=12, lh=1.5, gap=6, marker="—", color=BODY):
        for it in items:
            w = PW - 2 * MG - indent - 10
            lines = wrap(it, size, w)
            step = size * lh
            first = True
            for ln in lines:
                self.ensure(step)
                if first:
                    self.page.insert_text((MG + indent - 10, self.y + size * 0.82), marker,
                                          fontsize=size, fontname="F1", color=ACC)
                    first = False
                self.page.insert_text((MG + indent, self.y + size * 0.82), ln,
                                      fontsize=size, fontname="F1", color=color)
                self.y += step
            self.y += gap - 2

    def box(self, text, label=None, fill=CARD, accent=ACC):
        size = 9.2
        w = PW - 2 * MG - 34
        lines = wrap(text, size, w, FS)
        h = 16 + len(lines) * size * 1.5 + (16 if label else 0)
        self.ensure(h + 10)
        top = self.y
        self.page.draw_rect(fitz.Rect(MG, top, PW - MG, top + h), color=None, fill=fill)
        self.page.draw_rect(fitz.Rect(MG, top, MG + 2.6, top + h), color=None, fill=accent)
        yy = top + 13
        if label:
            self.page.insert_text((MG + 16, yy + 4), label.upper(), fontsize=7.2,
                                  fontname="F2", color=accent)
            yy += 15
        for ln in lines:
            self.page.insert_text((MG + 16, yy + size * 0.8), ln, fontsize=size,
                                  fontname="F3", color=(0.16, 0.15, 0.14))
            yy += size * 1.5
        self.y = top + h + 12

    def qa(self, q, a):
        self.ensure(56)
        self.y += 3
        lines = wrap(q, 9.6, PW - 2 * MG, FB)
        for ln in lines:
            self.ensure(15)
            self.page.insert_text((MG, self.y + 8), ln, fontsize=9.6, fontname="F2", color=INK)
            self.y += 13.6
        self.y += 2
        self.para(a, 9.1, BODY, F, lh=1.5, gap=10, maxw=PW - 2 * MG - 6, x=MG + 6)

    def rows(self, pairs, size=9.0, w1=150):
        for k, v in pairs:
            lines = wrap(v, size, PW - 2 * MG - w1 - 12)
            step = size * 1.45
            h = max(step * len(lines), step)
            self.ensure(h + 5)
            self.page.insert_text((MG, self.y + size * 0.8), k, fontsize=size,
                                  fontname="F2", color=INK)
            yy = self.y
            for ln in lines:
                self.page.insert_text((MG + w1, yy + size * 0.8), ln, fontsize=size,
                                      fontname="F1", color=BODY)
                yy += step
            self.y = yy + 4
            self.page.draw_line(fitz.Point(MG, self.y - 2), fitz.Point(PW - MG, self.y - 2),
                                color=(0.92, 0.91, 0.89), width=0.6)
            self.y += 4

    def save(self, path):
        self.doc.save(path, garbage=4, deflate=True)


