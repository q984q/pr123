def sld():
    s=prs.slides.add_slide(BL)
    bg=s.shapes.add_shape(MSO_SHAPE.RECTANGLE,0,0,prs.slide_width,prs.slide_height)
    bg.fill.solid(); bg.fill.fore_color.rgb=BG; bg.line.fill.background(); bg.shadow.inherit=False
    bg.text_frame.word_wrap=True
    return s
def rect(s,x,y,w,h,fill=None,shape=MSO_SHAPE.RECTANGLE):
    sh=s.shapes.add_shape(shape,Inches(x),Inches(y),Inches(w),Inches(h))
    if fill is None: sh.fill.background()
    else: sh.fill.solid(); sh.fill.fore_color.rgb=fill
    sh.line.fill.background(); sh.shadow.inherit=False
    sh.text_frame.text=""
    return sh
def txt(s,x,y,w,h,t,size=11,bold=False,color=MUT,align=PP_ALIGN.LEFT,sp=1.15,font=FONT,caps=False,anchor=MSO_ANCHOR.TOP,shrink=False):
    tb=s.shapes.add_textbox(Inches(x),Inches(y),Inches(w),Inches(h))
    tf=tb.text_frame; tf.word_wrap=True
    tf.margin_left=0; tf.margin_right=0; tf.margin_top=0; tf.margin_bottom=0
    tf.vertical_anchor=anchor
    tf.auto_size=None
    lines=t.split("\n")
    for i,ln in enumerate(lines):
        p=tf.paragraphs[0] if i==0 else tf.add_paragraph()
        p.alignment=align; p.line_spacing=sp
        r=p.add_run(); r.text=ln.upper() if caps else ln
        f=r.font; f.name=font; f.size=Pt(size); f.bold=bold; f.color.rgb=color
        if caps: r.font._rPr.set('cap','all')
    return tb
def kicker(s,t,y=0.62):
    txt(s,M,y,CW,0.28,t,8.5,True,ACC,sp=1.0,caps=True)
def h1(s,t,y=0.95,size=27,w=CW):
    txt(s,M,y,w,1.2,t,size,True,W,sp=1.02)
def hair(s,y,x=M,w=CW,color=LINE,h=0.010):
    rect(s,x,y,w,h,color)
def img(s,path,x,y,w,h):
    return s.shapes.add_picture(path,Inches(x),Inches(y),Inches(w),Inches(h))

